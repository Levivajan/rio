// Builds the Chromium WebUI bundles and their .grd files (docs/chromium/m2-ui-bridge.md).
//   node scripts/chromium/build-webui.mjs [--out out/webui]   frame, overlay and settings with the MojoBridge, plus
//                                                             clu_{frame,overlay,settings}_resources.grd
//   node scripts/chromium/build-webui.mjs --fake [--out out/webui-fake]   the ui:fake harness with the FakeBridge
// Every bundle is checked after the build: no inline script, style or event handler, no remote URL in HTML or CSS,
// no Node or Electron module, and (product bundles) no eval and no FakeBridge. The product overlay bundle also carries
// what the browser injects into pages (docs/chromium/m7.md): page/zap.js, and the blocker's page/blocker-rules.json and
// page/blocker-cosmetic.json (scripts/chromium/blocker/build.ts).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build, runnerImport } from 'vite'
import { ENTRIES, RENDERER, webuiConfig } from './webui-vite.mjs'

/** Files under `dir`, relative and sorted, with forward slashes. */
export function listFiles(dir) {
  const out = []
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name)
      if (statSync(p).isDirectory()) walk(p)
      else out.push(relative(dir, p).split('\\').join('/'))
    }
  }
  walk(dir)
  return out.sort()
}

const REMOTE = /(?:src|href)\s*=\s*["']?\s*(?:https?:)?\/\//i

/** Problems that would break under the WebUI CSP or load from the network. Empty when the bundle is clean. */
export function checkBundle(dir, { product }) {
  const problems = []
  for (const file of listFiles(dir)) {
    const text = /\.(html|js|css|svg)$/.test(file) ? readFileSync(join(dir, file), 'utf8') : ''
    if (file.endsWith('.html')) {
      for (const m of text.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
        if (!/\bsrc\s*=/.test(m[1] ?? '') || (m[2] ?? '').trim()) problems.push(`${file}: inline script`)
      }
      if (/<style\b/i.test(text)) problems.push(`${file}: inline <style>`)
      if (/\sstyle\s*=/i.test(text)) problems.push(`${file}: style attribute`)
      if (/\son[a-z]+\s*=/i.test(text)) problems.push(`${file}: inline event handler`)
      if (REMOTE.test(text)) problems.push(`${file}: remote URL`)
    }
    if (file.endsWith('.css') && /(?:url\(\s*["']?(?:https?:)?\/\/|@import\s+(?:url\()?\s*["']?(?:https?:)?\/\/)/i.test(text)) problems.push(`${file}: remote URL in CSS`)
    if (file.endsWith('.js')) {
      if (text.includes('__vite-browser-external')) problems.push(`${file}: a Node built-in reached the bundle`)
      if (/\bfrom\s*["']electron["']|require\(\s*["']electron["']\)/.test(text)) problems.push(`${file}: imports electron`)
      if (product && /\beval\(|new Function\(/.test(text)) problems.push(`${file}: eval or new Function`)
      if (product && text.includes('cluFakeHost')) problems.push(`${file}: the FakeBridge reached the product bundle`)
    }
  }
  if (!existsSync(join(dir, 'index.html'))) problems.push('index.html missing')
  return problems
}

const idrOf = (prefix, file) => `IDR_${prefix}_${file.toUpperCase().replace(/[^A-Z0-9]+/g, '_')}`

/** A grit file listing every file of one bundle; resource_path is the path under the WebUI's host. */
export function grdFor(name, prefix, dir, files) {
  // The blocker's lists are megabytes of JSON; ResourceBundle inflates gzip on load.
  const compress = (f) => (f.startsWith('page/') && f.endsWith('.json') ? ' compress="gzip"' : '')
  const includes = files.map((f) => `      <include name="${idrOf(prefix, f)}" file="${dir}/${f}" resource_path="${f}" type="BINDATA"${compress(f)} />`)
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/chromium/build-webui.mjs. Do not edit. -->
<grit latest_public_release="0" current_release="1">
  <outputs>
    <output filename="grit/${name}.h" type="rc_header">
      <emit emit_type='prepend'></emit>
    </output>
    <output filename="grit/${name}_map.cc" type="resource_file_map_source" />
    <output filename="grit/${name}_map.h" type="resource_map_header" />
    <output filename="${name}.pak" type="data_package" />
  </outputs>
  <release seq="1">
    <includes>
${includes.join('\n')}
    </includes>
  </release>
</grit>
`
}

/** Vite writes the html at its path under src/renderer; move it to the bundle root next to assets/. */
function hoistHtml(outDir, entry) {
  const from = join(outDir, entry)
  const depth = entry.split('/').length - 1
  const html = readFileSync(from, 'utf8').replaceAll(`${'../'.repeat(depth)}assets/`, './assets/')
  writeFileSync(join(outDir, 'index.html'), html)
  rmSync(join(outDir, entry.split('/')[0]), { recursive: true, force: true })
}

/** page/: the zap picker as one classic script (no imports, no module syntax: the browser runs it as page text), and
 * the blocker's resources. */
async function buildPage(dir) {
  await build({
    configFile: false,
    root: RENDERER,
    logLevel: 'warn',
    build: {
      outDir: join(dir, 'page'),
      emptyOutDir: false,
      target: 'chrome130',
      sourcemap: false,
      reportCompressedSize: false,
      lib: { entry: resolve(RENDERER, 'page/zap/entry.ts'), formats: ['iife'], name: 'cluZapPage', fileName: () => 'zap.js' }
    }
  })
  const { module } = await runnerImport(resolve('scripts/chromium/blocker/build.ts'), { configFile: false, logLevel: 'error' })
  module.buildBlocker(join(dir, 'page'))
}

export async function buildWebUi({ fake = false, out } = {}) {
  const outDir = resolve(out ?? (fake ? 'out/webui-fake' : 'out/webui'))
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })
  // The harness owns the bundle root, so it builds first; the WebUIs go in their own folders under it.
  const webuis = ['frame', 'overlay', 'settings'].map((b) => [b, join(outDir, b)])
  const bundles = fake ? [['harness', outDir], ...webuis] : webuis
  const problems = []
  for (const [bundle, dir] of bundles) {
    await build(webuiConfig({ bundle, fake, outDir: dir }))
    hoistHtml(dir, ENTRIES[bundle])
    if (bundle === 'harness') continue
    if (bundle === 'overlay' && !fake) await buildPage(dir)
    problems.push(...checkBundle(dir, { product: !fake }).map((p) => `${bundle}/${p}`))
    if (!fake) {
      const name = `clu_${bundle}_resources`
      writeFileSync(join(outDir, `${name}.grd`), grdFor(name, `CLU_${bundle.toUpperCase()}`, bundle, listFiles(dir)))
    }
  }
  if (problems.length) throw new Error(`WebUI bundle check failed:\n  ${problems.join('\n  ')}`)
  return outDir
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  const at = args.indexOf('--out')
  try {
    const dir = await buildWebUi({ fake: args.includes('--fake'), out: at >= 0 ? args[at + 1] : undefined })
    console.log(`WebUI bundles in ${relative(process.cwd(), dir)}`)
  } catch (e) {
    console.error(e instanceof Error ? e.message : e)
    process.exitCode = 1
  }
}

