// The look tokens for C++ (M11, docs/chromium/m11.md): src/shared/look/tokens.ts and targets.ts written as
// chromium/clu/browser/ui/views/frame/clu_look_tokens.h, so the native layout, the window buttons, dialogs, the color
// mixer and the CluLook* browser tests read the numbers the WebUIs use. gen-mojom.ts writes it with the rest.
import { probeId, probesFor } from '../../src/shared/look/compare'
import { LOOK_STATES, LOOK_TARGETS, resolveTarget } from '../../src/shared/look/targets'
import { LOOK, type LookColor, type LookColorName } from '../../src/shared/look/tokens'
import { SIDEBAR_WIDTH } from '../../src/shared/shell/layout'

export const LOOK_HEADER = 'chromium/clu/browser/ui/views/frame/clu_look_tokens.h'

const HEAD = '// Generated by scripts/chromium/gen-look.ts from src/shared/look. Do not edit; run `npm run gen:chromium`.'

/** ARGB, the SkColor layout. */
export function argb(c: LookColor): string {
  const b = (n: number) => Math.round(Math.min(255, Math.max(0, n))).toString(16).padStart(2, '0').toUpperCase()
  return `0x${b(c.a * 255)}${b(c.r)}${b(c.g)}${b(c.b)}u`
}

const f = (n: number) => (Number.isInteger(n) ? `${n}.f` : `${n}f`)
const snake = (s: string) => s.replace(/[A-Z]/g, (m) => `_${m.toLowerCase()}`)
const str = (s: string) => JSON.stringify(s)

export function lookTokenFiles(): [string, string][] {
  const names = Object.keys(LOOK.color.light) as LookColorName[]
  const palette = (mode: 'light' | 'dark') => names.map((n) => `    ${argb(LOOK.color[mode][n])},  // ${n}`).join('\n')
  const ctx = { sidebarWidth: SIDEBAR_WIDTH, windowHeight: 800 }
  const targets = LOOK_TARGETS.map((raw) => {
    const t = resolveTarget(raw, ctx)
    const e = t.expect
    const [unit, value, color, base] =
      'px' in e ? ['kPx', e.px, '0u', 'kNone'] :
      'ms' in e ? ['kMs', e.ms, '0u', 'kNone'] :
      'ratio' in e ? ['kRatio', e.ratio, '0u', 'kNone'] :
      'tintShare' in e ? ['kTintShare', e.tintShare, '0u', 'kTint'] :
      ['kColor', 0, argb(e.color), e.over === 'tint' ? 'kTint' : e.over === 'panel' ? 'kPanel' : 'kWhite']
    const native = 'native' in t.probe ? t.probe.native : ''
    return `    {${str(t.key)}, ${str(t.state)}, ${str(probeId(t.state, t.probe))}, ${str(native)}, TargetUnit::${unit}, ${value}, ${color}, TargetBase::${base}, ${t.tol}},`
  })
  const probes = Object.fromEntries(LOOK_STATES.map((s) => [s, { frame: probesFor(s, 'frame'), overlay: probesFor(s, 'overlay') }]))
  const tl = LOOK.window.trafficLights
  const h = `${HEAD}

#ifndef CLU_BROWSER_UI_VIEWS_FRAME_CLU_LOOK_TOKENS_H_
#define CLU_BROWSER_UI_VIEWS_FRAME_CLU_LOOK_TOKENS_H_

#include <cstdint>
#include <string_view>

// The look tokens (src/shared/look/tokens.ts), in points, milliseconds and ARGB colors.
namespace clu::look {

// The page card: inset from the window edges (and from the sidebar's edge on the left), radius and shadow.
inline constexpr int kCardInset = ${LOOK.card.inset};
inline constexpr float kCardRadius = ${f(LOOK.card.radius)};
inline constexpr float kCardShadowY = ${f(LOOK.card.shadow.y)};
inline constexpr float kCardShadowBlur = ${f(LOOK.card.shadow.blur)};
inline constexpr uint32_t kCardShadowColor = ${argb(LOOK.card.shadow.color)};

// The window: macOS draws the corners and the buttons; Clu centers the buttons on the sidebar's top row.
inline constexpr float kWindowCornerRadius = ${f(LOOK.window.cornerRadius)};
inline constexpr float kTrafficLightFirstCenterX = ${f(tl.firstCenterX)};
inline constexpr float kTrafficLightCenterY = ${f(tl.centerY)};
inline constexpr float kTrafficLightDiameter = ${f(tl.diameter)};
inline constexpr float kTrafficLightPitch = ${f(tl.pitch)};

// The sidebar docks in kSidebarShowMs and hides in kSidebarHideMs (0 would be one frame).
inline constexpr int kSidebarShowMs = ${LOOK.sidebar.showMs};
inline constexpr int kSidebarHideMs = ${LOOK.sidebar.hideMs};
// The hide's sampled curve: {ms, share of the card edge's travel}, linear between samples.
struct CurvePoint {
  int ms;
  double progress;
};
inline constexpr CurvePoint kSidebarHideCurve[] = {
${LOOK.sidebar.hideCurve.map(([ms, p]) => `    {${ms}, ${p}},`).join('\n')}
};

// Popover, dialog and menu radii the native surfaces would match.
inline constexpr float kDialogRadius = ${f(LOOK.dialog.radius)};
inline constexpr float kMenuRadius = ${f(LOOK.menu.radius)};

// Split panes (Chromium draws them; the layout asserts its radius matches) and the Peek card: radius, and its
// top and bottom inset from the window.
inline constexpr float kSplitRadius = ${f(LOOK.split.radius)};
inline constexpr float kPeekRadius = ${f(LOOK.peek.radius)};
inline constexpr int kPeekInsetY = ${LOOK.peek.insetY};

// The fixed colors, light and dark (LOOK.color in tokens.ts, same order).
struct Palette {
${names.map((n) => `  uint32_t ${snake(n)};`).join('\n')}
};
inline constexpr Palette kLight = {
${palette('light')}
};
inline constexpr Palette kDark = {
${palette('dark')}
};
// A space with no theme paints this gradient; the native frame color is its first stop.
inline constexpr uint32_t kDefaultTintFrom = ${argb(LOOK.defaultTint.from)};
inline constexpr uint32_t kDefaultTintTo = ${argb(LOOK.defaultTint.to)};
inline constexpr uint32_t kDefaultTintDark = ${argb(LOOK.defaultTint.dark)};

// The screenshot targets (src/shared/look/targets.ts), resolved for the default ${SIDEBAR_WIDTH} point sidebar. A kColor target
// is \`color\` composited over \`base\`; kTintShare is \`value\` of the tint over white.
enum class TargetUnit { kPx, kMs, kRatio, kColor, kTintShare };
enum class TargetBase { kNone, kTint, kPanel, kWhite };
struct Target {
  std::string_view key;
  std::string_view state;
  std::string_view probe_id;
  std::string_view native;  // set for values the browser test reads from Chromium
  TargetUnit unit;
  double value;
  uint32_t color;
  TargetBase base;
  double tolerance;
};
inline constexpr Target kTargets[] = {
${targets.join('\n')}
};

// measure.js probes per state and WebUI: {"<state>": {"frame": [{id, probe}], "overlay": [...]}}.
inline constexpr std::string_view kProbesJson = R"json(${JSON.stringify(probes)})json";

}  // namespace clu::look

#endif  // CLU_BROWSER_UI_VIEWS_FRAME_CLU_LOOK_TOKENS_H_
`
  return [[LOOK_HEADER, h]]
}
