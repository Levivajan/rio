// Writes src/shared/command/tlds.ts from the checked-in IANA snapshot src/shared/command/tlds-iana.txt (04-command F12). The output depends only on the snapshot: lowercase, deduped, sorted by code unit, no timestamps.
//   node scripts/gen-tlds.mjs           regenerate tlds.ts from the snapshot
//   node scripts/gen-tlds.mjs --fetch   refresh the snapshot from IANA first, then regenerate
//   node scripts/gen-tlds.mjs --stdout  print tlds.ts instead of writing it (the determinism test uses this)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const IANA_URL = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt'
const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'shared', 'command')
const snapshotPath = join(dir, 'tlds-iana.txt')
const outPath = join(dir, 'tlds.ts')

/** tlds.ts source for the IANA list text. Throws on a line that is not a TLD so a bad download never lands. */
export function renderTlds(text) {
  const lines = text.split(/\r?\n/).map((l) => l.trim())
  const version = lines.find((l) => l.startsWith('#'))?.replace(/^#\s*/, '') ?? 'unknown'
  const tlds = new Set()
  for (const line of lines) {
    if (line === '' || line.startsWith('#')) continue
    const tld = line.toLowerCase()
    if (!/^[a-z0-9-]{2,63}$/.test(tld)) throw new Error(`not a TLD: ${JSON.stringify(line)}`)
    tlds.add(tld)
  }
  if (tlds.size < 1000) throw new Error(`only ${tlds.size} TLDs, expected the full IANA list`)
  const sorted = [...tlds].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
  const rows = []
  for (let i = 0; i < sorted.length; i += 12) rows.push(`    '${sorted.slice(i, i + 12).join(' ')}'`)
  return [
    '// Generated by scripts/gen-tlds.mjs from tlds-iana.txt. Do not edit by hand.',
    `// IANA ${version}`,
    '',
    '/** Every IANA top-level domain, lowercase ASCII (IDN TLDs in their xn-- form). */',
    'export const TLDS: ReadonlySet<string> = new Set(',
    '  [',
    rows.join(',\n'),
    "  ].join(' ').split(' ')",
    ')',
    ''
  ].join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2)
  if (args.includes('--fetch')) {
    const res = await fetch(IANA_URL)
    if (!res.ok) throw new Error(`IANA answered ${res.status}`)
    const body = await res.text()
    renderTlds(body)
    writeFileSync(snapshotPath, body)
  }
  const source = renderTlds(readFileSync(snapshotPath, 'utf8'))
  if (args.includes('--stdout')) process.stdout.write(source)
  else writeFileSync(outPath, source)
}
